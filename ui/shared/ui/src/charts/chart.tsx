import * as RechartsPrimitive from "recharts"
import type { TooltipValueType } from "recharts"

// Format: { THEME_NAME: CSS_SELECTOR }
type Themes = { light: ""; dark: ".dark" }

const INITIAL_DIMENSION = { width: 320, height: 200 } as const
type TooltipNameType = number | string

export type ChartConfig = Record<
  string,
  {
    label?: React.ReactNode
    icon?: React.ComponentType
  } & (
    | { color?: string; theme?: never }
    | { color?: never; theme: Record<keyof Themes, string> }
  )
>

type ChartContextProps = {
  config: ChartConfig
}

const ChartContext = React.createContext<ChartContextProps | null>(null)

function useChart() {
  const context = React.useContext(ChartContext)

  if (!context) {
    throw new Error("useChart must be used within a <ChartContainer />")
  }

  return context
}

function ChartContainer({
  id,
  className,
  children,
  config,
  initialDimension = INITIAL_DIMENSION,
  style,
  ...props
}: React.ComponentProps<"div"> & {
  config: ChartConfig
  children: React.ComponentProps<
    typeof RechartsPrimitive.ResponsiveContainer
  >["children"]
  initialDimension?: {
    width: number
    height: number
  }
}) {
  const uniqueId = React.useId()
  const chartId = `chart-${id ?? uniqueId.replace(/:/g, "")}`

  return (
    <ChartContext.Provider value={{ config }}>
      <div
        data-slot="chart"
        data-chart={chartId}
        className={cn(
          "flex aspect-video justify-center text-xs [&_.recharts-cartesian-axis-tick_text]:fill-muted-foreground [&_.recharts-cartesian-grid_line[stroke='#ccc']]:stroke-border/50 [&_.recharts-curve.recharts-tooltip-cursor]:stroke-border [&_.recharts-dot[stroke='#fff']]:stroke-transparent [&_.recharts-layer]:outline-hidden [&_.recharts-polar-grid_[stroke='#ccc']]:stroke-border [&_.recharts-radial-bar-background-sector]:fill-muted [&_.recharts-rectangle.recharts-tooltip-cursor]:fill-muted [&_.recharts-reference-line_[stroke='#ccc']]:stroke-border [&_.recharts-sector]:outline-hidden [&_.recharts-sector[stroke='#fff']]:stroke-transparent [&_.recharts-surface]:outline-hidden",
          className
        )}
        style={{ ...chartStyleVars(config), ...style }}
        {...props}
      >
        <RechartsPrimitive.ResponsiveContainer
          initialDimension={initialDimension}
        >
          {children}
        </RechartsPrimitive.ResponsiveContainer>
      </div>
    </ChartContext.Provider>
  )
}

/**
 * Nasiko patch (ADR-0003): upstream injects a `<style dangerouslySetInnerHTML>`
 * built from config strings. Here colours become CSS custom properties set on
 * the container's `style` attribute instead — no HTML string, so a colour
 * coming from a generated surface cannot close the rule and inject CSS — and
 * every value is validated against a strict grammar first. Dark-theme values
 * use the `--color-<key>-dark` property, switched by the `.dark` rule in
 * tokens.css. `ChartStyle` is kept as a no-op export for API compatibility.
 */
const SAFE_COLOR = /^(#[0-9a-f]{3,8}|(?:rgb|rgba|hsl|hsla|oklch|oklab|lab|lch|color)\([0-9a-z.,%\s/-]{1,60}\)|var\(--[a-z0-9-]{1,40}\)|[a-z]{3,20})$/i

/** `true` when a colour string is safe to place in a CSS custom property. Exported for tests. */
function isSafeChartColor(value: unknown): value is string {
  return typeof value === "string" && value.length <= 80 && !/[^\S ]/.test(value) && SAFE_COLOR.test(value.trim())
}

function chartStyleVars(config: ChartConfig): React.CSSProperties {
  const vars: Record<string, string> = {}
  for (const [key, item] of Object.entries(config)) {
    if (!/^[a-z0-9_-]{1,40}$/i.test(key)) continue
    const light = item.theme?.light ?? item.color
    const dark = item.theme?.dark ?? item.color
    if (isSafeChartColor(light)) vars[`--color-${key}`] = light.trim()
    if (isSafeChartColor(dark)) vars[`--color-${key}-dark`] = dark.trim()
  }
  return vars as React.CSSProperties
}

