function SidebarMenuButton({
  render,
  isActive = false,
  variant = "default",
  size = "default",
  tooltip,
  className,
  ...props
}: useRender.ComponentProps<"button"> & {
  isActive?: boolean
  tooltip?: string | React.ComponentProps<typeof TooltipContent>
} & VariantProps<typeof sidebarMenuButtonVariants>) {
  const { isMobile, state } = useSidebar()

  const button = useRender({
    defaultTagName: "button",
    render,
    props: mergeProps<"button">(
      {
        ...dataAttrs({
          slot: "sidebar-menu-button",
          sidebar: "menu-button",
          size,
          active: isActive,
        }),
        className: cn(sidebarMenuButtonVariants({ variant, size }), className),
      },
      props
    ),
  })

  // Only the desktop rail shows tooltips. A hidden Radix tooltip still opens on focus and takes
  // the first Escape, which would stop Escape from closing the phone sheet (local edit).
  if (!tooltip || isMobile || state !== "collapsed") {
    return button
  }

  if (typeof tooltip === "string") {
    tooltip = {
      children: tooltip,
    }
  }

  return (
    <Tooltip>
      <TooltipTrigger render={button} />
      <TooltipContent
        side="right"
        align="center"
        hidden={state !== "collapsed" || isMobile}
        {...tooltip}
      />
    </Tooltip>
  )
}

