function DropdownMenuContent({
  onCloseAutoFocus,
  align = "start",
  alignOffset = 0,
  side = "bottom",
  sideOffset = 4,
  className,
  ...props
}: (MenuPrimitive.Popup.Props &
  Pick<
    MenuPrimitive.Positioner.Props,
    "align" | "alignOffset" | "side" | "sideOffset"
  >) & {
  onCloseAutoFocus?: AutoFocusHandler
}) {
  return (
    <MenuPrimitive.Portal container={usePortalContainer()}>
      <MenuPrimitive.Positioner
        className="isolate z-50 outline-none"
        align={align}
        alignOffset={alignOffset}
        side={side}
        sideOffset={sideOffset}
      >
        <MenuPrimitive.Popup
          data-slot="dropdown-menu-content"
          className={cn(
            "z-50 max-h-(--available-height) min-w-[8rem] origin-(--transform-origin) overflow-x-hidden overflow-y-auto rounded-md border bg-popover p-1 text-popover-foreground shadow-md data-closed:animate-out data-closed:fade-out-0 data-closed:zoom-out-95 data-open:animate-in data-open:fade-in-0 data-open:zoom-in-95 data-[side=bottom]:slide-in-from-top-2 data-[side=left]:slide-in-from-right-2 data-[side=right]:slide-in-from-left-2 data-[side=top]:slide-in-from-bottom-2",
            className
          )}
          {...props}
          finalFocus={focusProp(onCloseAutoFocus) ?? props.finalFocus}
        />
      </MenuPrimitive.Positioner>
    </MenuPrimitive.Portal>
  )
}

/** Whether a label sits inside a group: Base UI's GroupLabel throws outside one (error #31); Radix's Label didn't. */
const InGroupContext = React.createContext(false)

function DropdownMenuGroup({ ...props }: MenuPrimitive.Group.Props) {
  return (
    <InGroupContext value={true}>
      <MenuPrimitive.Group data-slot="dropdown-menu-group" {...props} />
    </InGroupContext>
  )
}

function DropdownMenuLabel({
  className,
  inset,
  ...props
}: MenuPrimitive.GroupLabel.Props & {
  inset?: boolean
}) {
  const classes = cn(
    "px-2 py-1.5 text-sm font-medium data-inset:pl-8",
    className
  )
  if (!React.use(InGroupContext)) {
    // A label outside a group (the lab's Radix menus use them freely): a plain heading row, as Radix's Label was.
    // A GroupLabel `render` prop has no meaning on the plain row.
    const { render, ...rest } = props
    return (
      <div
        data-slot="dropdown-menu-label"
        data-inset={inset}
        className={typeof classes === "string" ? classes : undefined}
        {...(rest as React.ComponentProps<"div">)}
      />
    )
  }
  return (
    <MenuPrimitive.GroupLabel
      data-slot="dropdown-menu-label"
      data-inset={inset}
      className={classes}
      {...props}
    />
  )
}

